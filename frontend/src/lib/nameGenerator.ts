function pick<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)]
}

export function generateName(race: Race): string {
  const parts = NAME_PARTS[race]
  return `${pick(parts.first)} ${pick(parts.last)}`
}
